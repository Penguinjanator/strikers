#!/usr/bin/env python3
"""Compile the settings Qt Linguist Online context for the game without Qt."""
import argparse
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/platform/online/panel_translations.inc'
LANGUAGES = ('de', 'fr', 'es')


def conversions(value):
    matches = re.findall(r'%(?:%|[+\- .0-9]*[sduf])', value)
    if '%' in re.sub(r'%(?:%|[+\- .0-9]*[sduf])', '', value):
        raise ValueError('unsupported printf conversion: ' + value)
    return ''.join(m[-1] for m in matches if m != '%%')


def generate():
    source = (ROOT / 'src/platform/online/panel_text.cpp').read_text(encoding="utf-8")
    entries = re.findall(r'\{ (T_\w+), "([sduf]*)", QT_TRANSLATE_NOOP\("Online", ("(?:[^"\\]|\\.)*")\) \}', source)
    catalogues = []
    for language in LANGUAGES:
        tree = ET.parse(ROOT / f'settings/i18n/strikers-settings_{language}.ts')
        catalogue = {}
        for context in tree.findall('context'):
            if context.findtext('name') != 'Online':
                continue
            for message in context.findall('message'):
                translation = message.find('translation')
                if translation is None or translation.get('type') in ('unfinished', 'obsolete', 'vanished'):
                    continue
                key = message.findtext('source')
                value = translation.text or ''
                if key in catalogue and catalogue[key] != value:
                    raise ValueError(f'{language}: ambiguous Online source {key}')
                catalogue[key] = value
        catalogues.append(catalogue)
    out = ['// GENERATED by tools/gen-online-translations.py from the Qt Linguist catalogues, do not edit.',
           'const Translation kTranslations[] = {']
    for key, args, literal in entries:
        english = json.loads(literal)
        if chr(0x2014) in english:
            raise ValueError(f'{key}: em dashes are not allowed')
        if conversions(english) != args:
            raise ValueError(f'{key}: invalid source format')
        values = []
        for language, catalogue in zip(LANGUAGES, catalogues):
            value = catalogue.get(english)
            if value and chr(0x2014) in value:
                raise ValueError(f'{language}: em dashes are not allowed in {key}')
            if not value or conversions(value) != args:
                raise ValueError(f'{language}: missing or invalid translation for {key}')
            values.append(json.dumps(value, ensure_ascii=False))
        out.append('    {' + key + ', {' + ', '.join(values) + '}},')
    out.append('};')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            parser.error('generated catalogue is stale; run tools/gen-online-translations.py')
    else:
        OUTPUT.write_text(result, encoding="utf-8")
